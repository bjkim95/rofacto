#!/usr/bin/env python3
"""Collect DiT4DiT RoboCasa GR1 rollouts and export clip-start-aligned condition clips.

This production-oriented collector separates live rollout from clip export:

1. Run a closed-loop live RoboCasa rollout and cache states/actions/RGB/camera poses.
2. For each clip window, freeze static RGB/depth at the clip-start state while following
   the live camera trajectory.
3. For each clip window, reset a collision-free shadow env to the same clip-start state
   and replay that clip's action sequence to render nominal robot mesh and EEF depth.

Only static RGB/depth are clip-start frozen. Nominal mesh and EEF depth are time-varying
action-condition videos generated by replaying the actions from the clip start.
"""

