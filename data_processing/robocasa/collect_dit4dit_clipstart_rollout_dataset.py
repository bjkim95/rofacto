def collect_live_rollout(
    *,
    args: argparse.Namespace,
    env,
    policy: Dit4DitPolicyClient,
    robosuite_module,
    mujoco_module,
    episode_index: int,
    episode_seed_value: int | None = None,
) -> dict[str, Any]:
    rollout_args = argparse.Namespace(
        warmstart_hdf5=args.warmstart_hdf5,
        warmstart_demo=args.warmstart_demo,
        warmstart_state_index=args.warmstart_state_index,
        seed=episode_seed(args, episode_index) if episode_seed_value is None else int(episode_seed_value),
    )
    obs = reset_rollout_start(env, rollout_args, robosuite_module)
    sim_env = low_env(env)
    model_xml = sim_env.sim.model.get_xml()
    ep_meta = json.dumps(jsonable(sim_env.get_ep_meta()), ensure_ascii=False, sort_keys=True)

    states_pre: list[np.ndarray] = []
    states_post: list[np.ndarray] = []
    rgb_frames: list[np.ndarray] = []
    camera_positions: list[np.ndarray] = []
    camera_quaternions: list[np.ndarray] = []
    rewards: list[float] = []
    successes: list[bool] = []
    action_records: dict[str, list[np.ndarray]] = {}
    step_count = 0
    chunk_count = 0
    terminal = False

    while step_count < args.max_steps and not terminal:
        chunk = unbatch_action_chunk(policy.step(obs))
        horizon = min(args.n_action_steps, min(value.shape[0] for value in chunk.values()))
        chunk_count += 1
        for local_idx in range(horizon):
            if step_count >= args.max_steps:
                break
            action = action_at(chunk, local_idx)
            states_pre.append(sim_env.sim.get_state().flatten().copy())
            pos, quat = current_camera_pose(sim_env, camera_name=args.camera, mujoco_module=mujoco_module)
            camera_positions.append(pos)
            camera_quaternions.append(quat)
            rgb_frames.append(sim_env.sim.render(height=args.height, width=args.width, camera_name=args.camera)[::-1].copy())
            for key, value in action.items():
                action_records.setdefault(key, []).append(value.copy())

            obs, reward, terminated, truncated, info = env.step(action)
            states_post.append(sim_env.sim.get_state().flatten().copy())
            success = safe_success(info)
            rewards.append(float(reward))
            successes.append(success)
            step_count += 1
            terminal = bool(terminated or truncated) or (args.terminate_on_success and any(successes))
            if step_count % 50 == 0 or terminal:
                print(
                    f"[worker {args.worker_rank:02d} episode {episode_index:03d}] "
                    f"step={step_count} success={bool(any(successes))} chunk={chunk_count}",
                    flush=True,
                )
            if terminal:
                break

    return {
        "model_xml": model_xml,
        "ep_meta": ep_meta,
        "states_pre": np.asarray(states_pre, dtype=np.float64),
        "states_post": np.asarray(states_post, dtype=np.float64),
        "rgb_frames": rgb_frames,
        "camera_positions": np.asarray(camera_positions, dtype=np.float64),
        "camera_quaternions": np.asarray(camera_quaternions, dtype=np.float64),
        "actions": {key: np.asarray(values, dtype=np.float32) for key, values in sorted(action_records.items())},
        "rewards": np.asarray(rewards, dtype=np.float32),
        "successes": np.asarray(successes, dtype=np.bool_),
        "chunks": int(chunk_count),
        "steps": int(step_count),
        "success": bool(any(successes)),
    }


def eef_center(env, eef_geom_ids: np.ndarray) -> np.ndarray:
    if len(eef_geom_ids) == 0:
        return np.full(3, np.nan, dtype=np.float64)
    return np.asarray(env.sim.data.geom_xpos[eef_geom_ids], dtype=np.float64).mean(axis=0)


def action_for_step(actions: dict[str, np.ndarray], index: int) -> dict[str, np.ndarray]:
    return {key: value[index].copy() for key, value in actions.items()}


def as_low_env(env):
    return low_env(env) if hasattr(env, "unwrapped") else env


def reset_env_to_state(env, *, state: np.ndarray, model_xml: str | None, ep_meta: str | None, robosuite_module) -> None:
    target_env = as_low_env(env)
    payload: dict[str, Any] = {"states": state}
    if model_xml is not None:
        payload["model"] = model_xml
    if ep_meta is not None:
        payload["ep_meta"] = ep_meta
    reset_to(target_env, payload, robosuite_module)


def render_static_clip(
    *,
    args: argparse.Namespace,
    static_env,
    static_robot_geom_ids: np.ndarray,
    rollout: dict[str, Any],
    start: int,
    robosuite_module,
    mujoco_module,
    robosuite_camera_utils,
) -> tuple[list[np.ndarray], list[np.ndarray]]:
    static_low = as_low_env(static_env)
    reset_env_to_state(
        static_low,
        state=rollout["states_pre"][start],
        model_xml=rollout["model_xml"],
        ep_meta=rollout["ep_meta"],
        robosuite_module=robosuite_module,
    )
    rgb_frames: list[np.ndarray] = []
    depth_frames: list[np.ndarray] = []
    for offset in range(args.source_span):
        frame_index = start + offset
        with override_camera_pose(
            static_low,
            camera_name=args.camera,
            position=rollout["camera_positions"][frame_index],
            quaternion=rollout["camera_quaternions"][frame_index],
            mujoco_module=mujoco_module,
        ):
            with hide_robot_scene(static_low, static_robot_geom_ids):
                depth = render_depth_colormap_frame(
                    static_low,
                    camera_name=args.camera,
                    width=args.width,
                    height=args.height,
                    near_m=args.depth_near_m,
                    far_m=args.depth_far_m,
                    invalid_color=None,
                    robosuite_camera_utils_module=robosuite_camera_utils,
                )
                rgb = static_low.sim.render(height=args.height, width=args.width, camera_name=args.camera)[::-1]
        rgb_frames.append(rgb.copy())
        depth_frames.append(depth.copy())
    return rgb_frames, depth_frames


def render_shadow_clip(
    *,
    args: argparse.Namespace,
    shadow_env,
    shadow_robot_geom_ids: np.ndarray,
    shadow_eef_geom_ids: np.ndarray,
    rollout: dict[str, Any],
    start: int,
    robosuite_module,
    mujoco_module,
    robosuite_camera_utils,
    background_rgb: np.ndarray,
    flat_robot_rgb: np.ndarray,
) -> tuple[list[np.ndarray], list[np.ndarray], list[float]]:
    shadow_low = as_low_env(shadow_env)
    if hasattr(shadow_env, "reset"):
        # Gymnasium's OrderEnforcing wrapper requires a wrapper-level reset before
        # step(), even though reset_to below overwrites the MuJoCo state.
        shadow_env.reset(seed=int(args.seed + args.worker_rank * 100000 + start))
    reset_env_to_state(
        shadow_low,
        state=rollout["states_pre"][start],
        model_xml=rollout["model_xml"],
        ep_meta=rollout["ep_meta"],
        robosuite_module=robosuite_module,
    )
    disable_geom_collisions(shadow_low, shadow_robot_geom_ids)
    mesh_frames: list[np.ndarray] = []
    depth_frames: list[np.ndarray] = []
    shadow_done = False
    for offset in range(args.source_span):
        action_index = start + offset
        action = action_for_step(rollout["actions"], action_index)
        if not shadow_done:
            _, _, terminated, truncated, _ = shadow_env.step(action)
            shadow_done = bool(terminated or truncated)
        with override_camera_pose(
            shadow_low,
            camera_name=args.camera,
            position=rollout["camera_positions"][action_index],
            quaternion=rollout["camera_quaternions"][action_index],
            mujoco_module=mujoco_module,
        ):
            mesh, _ = render_robot_only_outputs(
                shadow_low,
                camera_name=args.camera,
                width=args.width,
                height=args.height,
                robot_geom_ids=shadow_robot_geom_ids,
                background_rgb=background_rgb,
                rgb_style=args.robot_only_rgb_style,
                flat_robot_rgb=flat_robot_rgb,
                near_m=None,
                far_m=None,
                robosuite_camera_utils_module=robosuite_camera_utils,
            )
            _, eef_depth = render_robot_only_outputs(
                shadow_low,
                camera_name=args.camera,
                width=args.width,
                height=args.height,
                robot_geom_ids=shadow_eef_geom_ids,
                background_rgb=np.zeros((1, 1, 3), dtype=np.uint8),
                rgb_style=args.robot_only_rgb_style,
                flat_robot_rgb=flat_robot_rgb,
                near_m=args.robot_depth_near_m,
                far_m=args.robot_depth_far_m,
                robosuite_camera_utils_module=robosuite_camera_utils,
            )
        if eef_depth is None:
            raise RuntimeError("Expected shadow EEF depth frame")
        mesh_frames.append(mesh.copy())
        depth_frames.append(eef_depth.copy())

    eef_deltas: list[float] = []
    final_action_index = start + args.source_span - 1
    if final_action_index < len(rollout["states_post"]):
        shadow_center = eef_center(shadow_low, shadow_eef_geom_ids)
        reset_env_to_state(
            shadow_low,
            state=rollout["states_post"][final_action_index],
            model_xml=None,
            ep_meta=None,
            robosuite_module=robosuite_module,
        )
        live_center = eef_center(shadow_low, shadow_eef_geom_ids)
        eef_deltas.append(float(np.linalg.norm(shadow_center - live_center)))
    return mesh_frames, depth_frames, eef_deltas


def render_state_mesh_clip(
    *,
    args: argparse.Namespace,
    state_env,
    state_robot_geom_ids: np.ndarray,
    rollout: dict[str, Any],
    start: int,
    robosuite_module,
    mujoco_module,
    robosuite_camera_utils,
    background_rgb: np.ndarray,
    flat_robot_rgb: np.ndarray,
) -> list[np.ndarray]:
    state_low = as_low_env(state_env)
    mesh_frames: list[np.ndarray] = []
    for offset in range(args.source_span):
        frame_index = start + offset
        reset_env_to_state(
            state_low,
            state=rollout["states_pre"][frame_index],
            model_xml=None,
            ep_meta=None,
            robosuite_module=robosuite_module,
        )
        with override_camera_pose(
            state_low,
            camera_name=args.camera,
            position=rollout["camera_positions"][frame_index],
            quaternion=rollout["camera_quaternions"][frame_index],
            mujoco_module=mujoco_module,
        ):
            mesh, _ = render_robot_only_outputs(
                state_low,
                camera_name=args.camera,
                width=args.width,
                height=args.height,
                robot_geom_ids=state_robot_geom_ids,
                background_rgb=background_rgb,
                rgb_style=args.robot_only_rgb_style,
                flat_robot_rgb=flat_robot_rgb,
                near_m=None,
                far_m=None,
                robosuite_camera_utils_module=robosuite_camera_utils,
            )
        mesh_frames.append(mesh.copy())
    return mesh_frames


def export_episode_clips(
    *,
    args: argparse.Namespace,
    rollout: dict[str, Any],
    task_name: str,
    episode_name: str,
    static_env,
    shadow_env,
    robosuite_module,
    mujoco_module,
    robosuite_camera_utils,
) -> dict[str, Any]:
    episode_dir = args.out_root.expanduser() / task_name / episode_name
    starts = clip_starts(rollout["steps"], source_span=args.source_span, stride=args.clip_stride)
    background_rgb = np.asarray(args.background_color, dtype=np.uint8).reshape(1, 1, 3)
    flat_robot_rgb = np.asarray(args.robot_only_flat_color, dtype=np.uint8).reshape(1, 1, 3)
    static_low = as_low_env(static_env)
    shadow_low = as_low_env(shadow_env)

    reset_env_to_state(
        static_low,
        state=rollout["states_pre"][0],
        model_xml=rollout["model_xml"],
        ep_meta=rollout["ep_meta"],
        robosuite_module=robosuite_module,
    )
    static_robot_geom_ids = collect_robot_geom_ids(static_low)
    state_robot_geom_ids = static_robot_geom_ids
    reset_env_to_state(
        shadow_low,
        state=rollout["states_pre"][0],
        model_xml=rollout["model_xml"],
        ep_meta=rollout["ep_meta"],
        robosuite_module=robosuite_module,
    )
    shadow_robot_geom_ids = collect_robot_geom_ids(shadow_low)
    shadow_eef_geom_ids = collect_eef_geom_ids(shadow_low)

    clips: list[dict[str, Any]] = []
    delta_values: list[float] = []
    for clip_index, start in enumerate(starts):
        end = start + args.source_span - 1
        stem = f"{episode_name}__{args.camera_tag}__c{clip_index:03d}_{start:04d}-{end:04d}"
        if args.skip_existing and all_clip_outputs_exist(episode_dir, stem):
            clips.append({"stem": stem, "start": start, "end": end, "skipped": True})
            continue

        dynamic_frames = rollout["rgb_frames"][start : start + args.source_span]
        static_rgb, static_depth = render_static_clip(
            args=args,
            static_env=static_env,
            static_robot_geom_ids=static_robot_geom_ids,
            rollout=rollout,
            start=start,
            robosuite_module=robosuite_module,
            mujoco_module=mujoco_module,
            robosuite_camera_utils=robosuite_camera_utils,
        )
        shadow_mesh, shadow_depth, eef_deltas = render_shadow_clip(
            args=args,
            shadow_env=shadow_env,
            shadow_robot_geom_ids=shadow_robot_geom_ids,
            shadow_eef_geom_ids=shadow_eef_geom_ids,
            rollout=rollout,
            start=start,
            robosuite_module=robosuite_module,
            mujoco_module=mujoco_module,
            robosuite_camera_utils=robosuite_camera_utils,
            background_rgb=background_rgb,
            flat_robot_rgb=flat_robot_rgb,
        )
        state_mesh = None
        if args.write_state_mesh:
            state_mesh = render_state_mesh_clip(
                args=args,
                state_env=static_env,
                state_robot_geom_ids=state_robot_geom_ids,
                rollout=rollout,
                start=start,
                robosuite_module=robosuite_module,
                mujoco_module=mujoco_module,
                robosuite_camera_utils=robosuite_camera_utils,
                background_rgb=background_rgb,
                flat_robot_rgb=flat_robot_rgb,
            )
        delta_values.extend(eef_deltas)

        outputs = {
            "videos": episode_dir / "videos_clips81" / f"{stem}.mp4",
            "static": episode_dir / "static_videos_clips81" / f"{stem}.mp4",
            "scene_depth": episode_dir / "stereo_depth_videos_clips81" / f"{stem}.mp4",
            "mesh": episode_dir / "robot_mesh_videos_nominal_clips81" / f"{stem}.mp4",
            "state_mesh": episode_dir / "robot_mesh_videos_state_clips81" / f"{stem}.mp4",
            "eef_depth": episode_dir / "robot_eef_nominal_depth_videos_clips81" / f"{stem}.mp4",
        }
        write_resampled_clip(
            outputs["videos"],
            dynamic_frames,
            source_fps=args.source_fps,
            clip_fps=args.clip_fps,
            clip_frames=args.clip_frames,
            overwrite=args.overwrite,
        )
        write_resampled_clip(
            outputs["static"],
            static_rgb,
            source_fps=args.source_fps,
            clip_fps=args.clip_fps,
            clip_frames=args.clip_frames,
            overwrite=args.overwrite,
        )
        write_resampled_clip(
            outputs["scene_depth"],
            static_depth,
            source_fps=args.source_fps,
            clip_fps=args.clip_fps,
            clip_frames=args.clip_frames,
            overwrite=args.overwrite,
        )
        write_resampled_clip(
            outputs["mesh"],
            shadow_mesh,
            source_fps=args.source_fps,
            clip_fps=args.clip_fps,
            clip_frames=args.clip_frames,
            overwrite=args.overwrite,
        )
        write_resampled_clip(
            outputs["eef_depth"],
            shadow_depth,
            source_fps=args.source_fps,
            clip_fps=args.clip_fps,
            clip_frames=args.clip_frames,
            overwrite=args.overwrite,
        )
        if state_mesh is not None:
            write_resampled_clip(
                outputs["state_mesh"],
                state_mesh,
                source_fps=args.source_fps,
                clip_fps=args.clip_fps,
                clip_frames=args.clip_frames,
                overwrite=args.overwrite,
            )
        prompt_path = episode_dir / "videos_clips81_prompts_qwen3vl" / f"{stem}.json"
        write_prompt_json(
            prompt_path,
            args=args,
            task_name=task_name,
            episode_name=episode_name,
            stem=stem,
            clip_index=clip_index,
            start=start,
        )
        clips.append(
            {
                "stem": stem,
                "start": int(start),
                "end": int(end),
                "skipped": False,
                "video": str(outputs["videos"]),
            }
        )
        print(
            f"[worker {args.worker_rank:02d}] exported {episode_name} clip {clip_index + 1}/{len(starts)}",
            flush=True,
        )

    return {
        "episode": episode_name,
        "steps": int(rollout["steps"]),
        "success": bool(rollout["success"]),
        "num_clips": len(starts),
        "clips": clips,
        "eef_delta_mean_m": float(np.mean(delta_values)) if delta_values else None,
        "eef_delta_max_m": float(np.max(delta_values)) if delta_values else None,
    }


def write_episode_actions(episode_dir: Path, rollout: dict[str, Any], *, write_state_cache: bool = True) -> None:
    episode_dir.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        episode_dir / "rollout_actions_and_success.npz",
        **{key.replace(".", "_"): value for key, value in rollout["actions"].items()},
        rewards=rollout["rewards"],
        successes=rollout["successes"],
    )
    if write_state_cache:
        np.savez_compressed(
            episode_dir / "rollout_states_and_cameras.npz",
            states_pre=rollout["states_pre"],
            states_post=rollout["states_post"],
            camera_positions=rollout["camera_positions"],
            camera_quaternions=rollout["camera_quaternions"],
        )
        (episode_dir / "rollout_model.xml.gz").write_bytes(gzip.compress(rollout["model_xml"].encode("utf-8")))
        (episode_dir / "rollout_ep_meta.json").write_text(rollout["ep_meta"] + "\n", encoding="utf-8")


def main() -> None:
    args = parse_args()
    configure_mujoco_gl(args.mujoco_gl)
    if args.depth_far_m <= args.depth_near_m:
        raise ValueError("--depth-far-m must be greater than --depth-near-m")
    if args.robot_depth_far_m <= args.robot_depth_near_m:
        raise ValueError("--robot-depth-far-m must be greater than --robot-depth-near-m")
    if args.source_span <= int(source_indices_for_clip(args.clip_frames, args.source_fps, args.clip_fps).max()):
        raise ValueError("--source-span is too short for clip fps/frame settings")
    if args.clip_stride <= 0:
        raise ValueError("--clip-stride must be positive")

    task_specs = parse_task_specs(args)
    if args.task_name is not None and len(task_specs) > 1:
        raise ValueError("--task-name is only supported for single-task collection")
    episode_schedule = build_episode_schedule(args, task_specs)
    args.out_root = args.out_root.expanduser()
    args.out_root.mkdir(parents=True, exist_ok=True)

    runtime_args = argparse.Namespace(mujoco_gl=args.mujoco_gl)
    mujoco_module, robosuite_module, robosuite_camera_utils = import_runtime_modules(runtime_args)
    policy = Dit4DitPolicyClient(
        policy_ckpt_path=args.policy_ckpt_path.expanduser(),
        host=args.host,
        port=args.port,
        image_size=tuple(args.image_size),
        n_action_steps=args.n_action_steps,
        num_ddim_steps=args.num_ddim_steps,
    )
    live_env = None
    static_env = None
    shadow_env = None
    current_env_name = None

    summaries: list[dict[str, Any]] = []
    start_time = time.time()
    try:
        for assignment in episode_schedule:
            episode_index = int(assignment["episode_index"])
            task_spec = assignment
            env_name = task_spec["env_name"]
            task_name = args.task_name or task_spec["task_name"]
            global_index = int(assignment["global_index"])
            task_episode_index = assignment.get("task_episode_index")
            episode_name = f"{task_name}_dit4dit_w{args.worker_rank:02d}_e{global_index:06d}"
            episode_dir = args.out_root / task_name / episode_name
            if args.skip_existing and episode_dir.exists():
                nominal_complete = episode_has_complete_nominal_outputs(episode_dir)
                state_cache_exists = (episode_dir / "rollout_states_and_cameras.npz").is_file()
                state_complete = (not args.write_state_mesh) or episode_has_complete_state_mesh_outputs(episode_dir)
                if nominal_complete and (state_complete or not state_cache_exists):
                    print(
                        f"[worker {args.worker_rank:02d}] skip existing {episode_name}: "
                        "complete reusable outputs already present",
                        flush=True,
                    )
                    continue
                print(
                    f"[worker {args.worker_rank:02d}] cleanup incomplete {episode_name}: "
                    f"nominal_complete={nominal_complete} state_cache={state_cache_exists} "
                    f"state_complete={state_complete}",
                    flush=True,
                )
                shutil.rmtree(episode_dir)
            if current_env_name != env_name:
                if live_env is not None:
                    live_env.close()
                if static_env is not None:
                    static_env.close()
                if shadow_env is not None:
                    shadow_env.close()
                live_env = make_env(env_name, seed=args.seed)
                static_env = make_env(env_name, seed=args.seed + 17)
                shadow_env = make_env(env_name, seed=args.seed + 31)
                current_env_name = env_name
            seed_value = scheduled_episode_seed(args, assignment)
            print(
                f"[worker {args.worker_rank:02d}] collecting {episode_name} env={env_name} "
                f"task_episode={task_episode_index} seed={seed_value}",
                flush=True,
            )
            rollout_start = time.time()
            rollout = collect_live_rollout(
                args=args,
                env=live_env,
                policy=policy,
                robosuite_module=robosuite_module,
                mujoco_module=mujoco_module,
                episode_index=episode_index,
                episode_seed_value=seed_value,
            )
            if args.write_actions:
                write_episode_actions(episode_dir, rollout, write_state_cache=args.write_state_cache)
            clip_summary = export_episode_clips(
                args=args,
                rollout=rollout,
                task_name=task_name,
                episode_name=episode_name,
                static_env=static_env,
                shadow_env=shadow_env,
                robosuite_module=robosuite_module,
                mujoco_module=mujoco_module,
                robosuite_camera_utils=robosuite_camera_utils,
            )
            clip_summary["seconds"] = round(time.time() - rollout_start, 3)
            clip_summary["global_index"] = global_index
            clip_summary["task_episode_index"] = task_episode_index
            clip_summary["env_name"] = env_name
            summaries.append(clip_summary)
            print(
                f"[worker {args.worker_rank:02d}] done {episode_name}: "
                f"steps={clip_summary['steps']} clips={clip_summary['num_clips']} "
                f"success={clip_summary['success']} seconds={clip_summary['seconds']}",
                flush=True,
            )
    finally:
        policy.close()
        if live_env is not None:
            live_env.close()
        if static_env is not None:
            static_env.close()
        if shadow_env is not None:
            shadow_env.close()

    dataset_lines: list[str] = []
    data_root = args.out_root.parent.parent if args.out_root.name == "gr1_dit4dit_clipstart_480x832" else None
    for summary in summaries:
        for clip in summary["clips"]:
            if "video" in clip:
                video_path = Path(clip["video"])
                try:
                    rel = video_path.relative_to(args.out_root.parents[2])
                except Exception:
                    rel = video_path
                dataset_lines.append(str(rel))

    worker_summary = {
        "task": task_specs[0]["task_name"] if len(task_specs) == 1 else "balanced_multi_task",
        "tasks": task_specs,
        "task_block_size": int(args.task_block_size),
        "task_schedule": args.task_schedule,
        "episodes_per_task": args.episodes_per_task,
        "worker_rank": int(args.worker_rank),
        "world_size": int(args.world_size),
        "n_episodes": int(len(episode_schedule)),
        "max_steps": int(args.max_steps),
        "clip_stride": int(args.clip_stride),
        "source_span": int(args.source_span),
        "total_seconds": round(time.time() - start_time, 3),
        "episodes": summaries,
        "total_clips": int(sum(item["num_clips"] for item in summaries)),
        "dataset_lines": dataset_lines,
    }
    summary_path = args.out_root / f"worker_{args.worker_rank:02d}_summary.json"
    summary_path.write_text(json.dumps(worker_summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    list_path = args.out_root / f"worker_{args.worker_rank:02d}_videos_clips81.txt"
    list_path.write_text("\n".join(dataset_lines) + ("\n" if dataset_lines else ""), encoding="utf-8")
    print(json.dumps(worker_summary, indent=2, sort_keys=True), flush=True)


if __name__ == "__main__":
    main()
