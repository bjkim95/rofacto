    videos_dir = episode_dir / "videos_clips81"
    if not videos_dir.is_dir():
        return False
    stems = sorted(path.stem for path in videos_dir.glob("*.mp4"))
    if not stems:
        return False
    return all(all_clip_outputs_exist(episode_dir, stem) for stem in stems)


