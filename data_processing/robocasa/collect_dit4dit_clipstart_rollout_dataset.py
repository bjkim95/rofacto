def jsonable(value: Any) -> Any:
    if isinstance(value, dict):
        return {str(k): jsonable(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [jsonable(v) for v in value]
    if isinstance(value, np.ndarray):
        return value.tolist()
    if isinstance(value, np.generic):
        return value.item()
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    return str(value)


def task_name_from_env_id(env_name: str) -> str:
    class_name = env_name.split("/")[-1]
    for suffix in (
        "_GR1ArmsAndWaistFourierHands_Env",
        "_GR1ArmsOnlyFourierHands_Env",
        "_GR1FixedLowerBodyFourierHands_Env",
        "_Env",
    ):
        if class_name.endswith(suffix):
            return class_name[: -len(suffix)]
    return class_name


def env_id_from_task_spec(task_spec: str) -> str:
    task_spec = task_spec.strip()
    if not task_spec:
        raise ValueError("Empty task spec")
    if "/" in task_spec:
        return task_spec
    class_name = task_spec
    if not class_name.endswith("_Env"):
        class_name = f"{class_name}{DEFAULT_GR1_ENV_SUFFIX}"
    return f"gr1_unified/{class_name}"


def parse_task_specs(args: argparse.Namespace) -> list[dict[str, str]]:
    raw_specs: list[str] = []
    if args.task_list_path is not None:
        for line in args.task_list_path.expanduser().read_text(encoding="utf-8").splitlines():
            spec = line.split("#", 1)[0].strip()
            if spec:
                raw_specs.append(spec)
    if args.task_list:
        raw_specs.extend(spec.strip() for spec in args.task_list.split(",") if spec.strip())
    if not raw_specs:
        env_name = args.env_name
        raw_specs = [env_name]

    task_specs = []
    seen: set[str] = set()
    for raw_spec in raw_specs:
        env_name = env_id_from_task_spec(raw_spec)
        task_name = task_name_from_env_id(env_name)
        if env_name in seen:
            continue
        seen.add(env_name)
        task_specs.append({"env_name": env_name, "task_name": task_name})
    if not task_specs:
        raise ValueError("No tasks configured")
    return task_specs


def episode_seed(args: argparse.Namespace, episode_index: int) -> int:
    return int(args.seed + args.worker_rank * 100000 + episode_index)


def scheduled_episode_seed(args: argparse.Namespace, assignment: dict[str, Any]) -> int:
    if "global_index" in assignment:
        return int(args.seed + int(assignment["global_index"]))
    return episode_seed(args, int(assignment["episode_index"]))


def global_episode_index(args: argparse.Namespace, episode_index: int) -> int:
    return int(args.worker_rank * args.n_episodes + episode_index)


def episode_name_for(args: argparse.Namespace, task_name: str, episode_index: int) -> str:
    global_index = global_episode_index(args, episode_index)
    return f"{task_name}_dit4dit_w{args.worker_rank:02d}_e{global_index:06d}"


def task_spec_for_episode(
    args: argparse.Namespace,
    task_specs: list[dict[str, str]],
    episode_index: int,
) -> dict[str, str]:
    if args.task_block_size <= 0:
        raise ValueError("--task-block-size must be positive")
    task_index = (global_episode_index(args, episode_index) // args.task_block_size) % len(task_specs)
    return task_specs[task_index]


def build_episode_schedule(args: argparse.Namespace, task_specs: list[dict[str, str]]) -> list[dict[str, Any]]:
    if args.task_schedule == "round_robin":
        schedule = []
        for episode_index in range(args.n_episodes):
            task_spec = task_spec_for_episode(args, task_specs, episode_index)
            schedule.append(
                {
                    **task_spec,
                    "episode_index": episode_index,
                    "global_index": global_episode_index(args, episode_index),
                    "task_episode_index": None,
                }
            )
        return schedule

    if args.episodes_per_task is None or args.episodes_per_task <= 0:
        raise ValueError("--episodes-per-task must be positive for --task-schedule task_major")
    if args.world_size <= 0:
        raise ValueError("--world-size must be positive")

    total = len(task_specs) * int(args.episodes_per_task)
    start = total * int(args.worker_rank) // int(args.world_size)
    end = total * (int(args.worker_rank) + 1) // int(args.world_size)
    schedule = []
    for local_index, global_index in enumerate(range(start, end)):
        task_index = global_index // int(args.episodes_per_task)
        task_episode_index = global_index % int(args.episodes_per_task)
        task_spec = task_specs[task_index]
        schedule.append(
            {
                **task_spec,
                "episode_index": local_index,
                "global_index": global_index,
                "task_episode_index": task_episode_index,
            }
        )
    return schedule


def clip_starts(num_steps: int, *, source_span: int, stride: int) -> list[int]:
    if num_steps < source_span:
        return []
    return list(range(0, num_steps - source_span + 1, stride))


def write_resampled_clip(
    path: Path,
    frames: list[np.ndarray] | np.ndarray,
    *,
    source_fps: float,
    clip_fps: float,
    clip_frames: int,
    overwrite: bool,
) -> None:
    frames_list = list(frames)
    if not frames_list:
        raise ValueError(f"No frames provided for {path}")
    if path.exists():
        if not overwrite:
            raise FileExistsError(f"Output exists: {path}")
        path.unlink()
    path.parent.mkdir(parents=True, exist_ok=True)
    source_indices = source_indices_for_clip(clip_frames, source_fps, clip_fps)
    writer = VideoWriter(
        path,
        fps=clip_fps,
        frame_size=(frames_list[0].shape[1], frames_list[0].shape[0]),
        input_colorspace="rgb",
    )
    try:
        for idx in source_indices:
            writer.write(frames_list[int(idx)])
    finally:
        writer.close()


